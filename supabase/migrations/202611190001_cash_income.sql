-- Catatan pemasukan manual untuk kas Marawis.
create table if not exists public.cash_income (
  id bigint generated by default as identity primary key,
  title text not null,
  amount bigint not null check (amount > 0),
  income_date date not null default current_date,
  notes text,
  recorded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists cash_income_date_idx
  on public.cash_income(income_date desc);

alter table public.cash_income enable row level security;

drop policy if exists "Admins manage cash income" on public.cash_income;
create policy "Admins manage cash income"
on public.cash_income
for all
to authenticated
using (public.is_marawis_admin())
with check (public.is_marawis_admin());

grant select, insert, update, delete on public.cash_income to authenticated;
grant usage, select on sequence public.cash_income_id_seq to authenticated;
