create table if not exists public.multiplayer_rooms (
  id uuid primary key default gen_random_uuid(),
  room_code text not null unique check (room_code ~ '^[0-9]{6}$'),
  game_type text not null check (game_type in ('quiz_arena','who_leader','draw_guess')),
  host_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'waiting' check (status in ('waiting','playing','finished')),
  max_players integer not null default 10 check (max_players between 2 and 10),
  game_state jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.multiplayer_players (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.multiplayer_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null,
  score integer not null default 0,
  joined_at timestamptz not null default now(),
  unique(room_id,user_id)
);
create table if not exists public.multiplayer_events (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.multiplayer_rooms(id) on delete cascade,
  actor_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null check (event_type in ('answer','vote','draw','guess','system')),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.multiplayer_rooms enable row level security;
alter table public.multiplayer_players enable row level security;
alter table public.multiplayer_events enable row level security;

create policy "Authenticated users can view waiting rooms" on public.multiplayer_rooms
for select to authenticated using (
  status = 'waiting' or host_id = (select auth.uid()) or exists (
    select 1 from public.multiplayer_players p where p.room_id = multiplayer_rooms.id and p.user_id = (select auth.uid())
  )
);
create policy "Only staff can create multiplayer rooms" on public.multiplayer_rooms
for insert to authenticated with check (
  host_id = (select auth.uid()) and exists (
    select 1 from public.profiles pr where pr.id = (select auth.uid()) and pr.role in ('pengurus','pembina')
  )
);
create policy "Only room host staff can update rooms" on public.multiplayer_rooms
for update to authenticated using (
  host_id = (select auth.uid()) and exists (
    select 1 from public.profiles pr where pr.id = (select auth.uid()) and pr.role in ('pengurus','pembina')
  )
) with check (
  host_id = (select auth.uid()) and exists (
    select 1 from public.profiles pr where pr.id = (select auth.uid()) and pr.role in ('pengurus','pembina')
  )
);
create policy "Room host staff can delete rooms" on public.multiplayer_rooms
for delete to authenticated using (
  host_id = (select auth.uid()) and exists (
    select 1 from public.profiles pr where pr.id = (select auth.uid()) and pr.role in ('pengurus','pembina')
  )
);

-- Player names and scores are non-sensitive lobby information; only authenticated users can read them.
create policy "Authenticated users can view multiplayer player names" on public.multiplayer_players
for select to authenticated using (true);
create policy "Members can join waiting rooms" on public.multiplayer_players
for insert to authenticated with check (
  user_id = (select auth.uid()) and exists (
    select 1 from public.multiplayer_rooms r where r.id = room_id and r.status = 'waiting'
      and (select count(*) from public.multiplayer_players p where p.room_id = r.id) < r.max_players
  )
);
create policy "Players can update own score" on public.multiplayer_players
for update to authenticated using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));
create policy "Players can leave their own room" on public.multiplayer_players
for delete to authenticated using (user_id = (select auth.uid()));

create policy "Room participants can read game events" on public.multiplayer_events
for select to authenticated using (
  exists (select 1 from public.multiplayer_players p where p.room_id = multiplayer_events.room_id and p.user_id = (select auth.uid()))
  or exists (select 1 from public.multiplayer_rooms r where r.id = multiplayer_events.room_id and r.host_id = (select auth.uid()))
);
create policy "Room participants can submit game events" on public.multiplayer_events
for insert to authenticated with check (
  actor_id = (select auth.uid()) and exists (
    select 1 from public.multiplayer_players p where p.room_id = multiplayer_events.room_id and p.user_id = (select auth.uid())
  )
  and (event_type <> 'draw' or exists (
    select 1 from public.multiplayer_rooms r where r.id = multiplayer_events.room_id and r.host_id = (select auth.uid())
  ))
  and (event_type <> 'guess' or not (payload ? 'accepted') or exists (
    select 1 from public.multiplayer_rooms r where r.id = multiplayer_events.room_id and r.host_id = (select auth.uid())
  ))
);

grant select, insert, update, delete on public.multiplayer_rooms to authenticated;
grant select, insert, update, delete on public.multiplayer_players to authenticated;
grant select, insert on public.multiplayer_events to authenticated;
grant usage, select on sequence public.multiplayer_events_id_seq to authenticated;

