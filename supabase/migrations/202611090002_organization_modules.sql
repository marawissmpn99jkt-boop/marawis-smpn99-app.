-- Notifikasi hanya dapat dibaca dan ditandai oleh pemiliknya; admin dapat membuat/mengelola.
drop policy if exists "Users read own notifications" on public.notifications;
create policy "Users read own notifications" on public.notifications
for select to authenticated
using (user_id = (select auth.uid()) or public.is_marawis_admin());
drop policy if exists "Users update own notifications" on public.notifications;
create policy "Users update own notifications" on public.notifications
for update to authenticated
using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));
drop policy if exists "Admins manage notifications" on public.notifications;
create policy "Admins manage notifications" on public.notifications
for all to authenticated
using (public.is_marawis_admin())
with check (public.is_marawis_admin());

