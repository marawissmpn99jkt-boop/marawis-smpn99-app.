create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  audience text not null default 'all'
    check (audience in ('all', 'anggota', 'admin')),
  is_published boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  location text,
  starts_at timestamptz not null,
  ends_at timestamptz,
  activity_type text not null default 'latihan'
    check (activity_type in ('latihan', 'rapat', 'penampilan', 'acara', 'lainnya')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint activities_valid_time check (ends_at is null or ends_at >= starts_at)
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  activity_id bigint not null references public.activities(id) on delete cascade,
  member_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'hadir'
    check (status in ('hadir', 'izin', 'sakit', 'alpa')),
  notes text,
  marked_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (activity_id, member_id)
);

create table if not exists public.cash_payments (
  id bigint generated by default as identity primary key,
  member_id uuid not null references public.profiles(id) on delete cascade,
  amount bigint not null check (amount > 0),
  payment_period text not null,
  payment_method text not null default 'tunai'
    check (payment_method in ('tunai', 'transfer', 'lainnya')),
  proof_url text,
  status text not null default 'menunggu'
    check (status in ('menunggu', 'diterima', 'ditolak')),
  notes text,
  verified_by uuid references public.profiles(id) on delete set null,
  verified_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.cash_expenses (
  id bigint generated by default as identity primary key,
  title text not null,
  amount bigint not null check (amount > 0),
  expense_date date not null default current_date,
  notes text,
  recorded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.work_programs (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  person_in_charge text,
  start_date date,
  due_date date,
  status text not null default 'rencana'
    check (status in ('rencana', 'berjalan', 'selesai', 'ditunda')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.program_tasks (
  id bigint generated by default as identity primary key,
  program_id bigint not null references public.work_programs(id) on delete cascade,
  title text not null,
  assigned_to uuid references public.profiles(id) on delete set null,
  due_date date,
  status text not null default 'belum'
    check (status in ('belum', 'proses', 'selesai')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.member_scores (
  id bigint generated by default as identity primary key,
  member_id uuid not null references public.profiles(id) on delete cascade,
  score_type text not null
    check (score_type in ('keaktifan', 'kedisiplinan', 'kontribusi', 'prestasi')),
  points integer not null check (points between 0 and 100),
  notes text,
  assessed_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  body text not null,
  related_type text,
  related_id bigint,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id) on delete set null,
  action text not null,
  target_table text not null,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists announcements_created_at_idx on public.announcements(created_at desc);
create index if not exists activities_starts_at_idx on public.activities(starts_at);
create index if not exists attendance_member_idx on public.attendance(member_id);
create index if not exists attendance_activity_idx on public.attendance(activity_id);
create index if not exists cash_payments_member_idx on public.cash_payments(member_id, created_at desc);
create index if not exists cash_payments_status_idx on public.cash_payments(status);
create index if not exists notifications_user_idx on public.notifications(user_id, created_at desc);
create index if not exists member_scores_member_idx on public.member_scores(member_id);

