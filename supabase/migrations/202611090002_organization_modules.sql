-- Pengumuman: audiens hanya bisa membaca pengumuman yang ditujukan kepadanya.
drop policy if exists "Read published announcements" on public.announcements;
create policy "Read published announcements" on public.announcements
for select to authenticated
using (
  is_published and (
    audience = 'all'
    or (audience = 'anggota' and exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid()) and p.role = 'anggota'
    ))
    or (audience = 'admin' and public.is_marawis_admin())
  )
  or public.is_marawis_admin()
);
drop policy if exists "Admins manage announcements" on public.announcements;
create policy "Admins manage announcements" on public.announcements
for all to authenticated
using (public.is_marawis_admin())
with check (public.is_marawis_admin());

-- Jadwal: seluruh pengguna login dapat membaca, admin mengelola.
drop policy if exists "Authenticated read activities" on public.activities;
create policy "Authenticated read activities" on public.activities
for select to authenticated using (true);
drop policy if exists "Admins manage activities" on public.activities;
create policy "Admins manage activities" on public.activities
for all to authenticated
using (public.is_marawis_admin())
with check (public.is_marawis_admin());

-- Absensi: anggota hanya melihat absensi dirinya; admin mengelola semuanya.
drop policy if exists "Read own attendance or admin" on public.attendance;
create policy "Read own attendance or admin" on public.attendance
for select to authenticated
using (member_id = (select auth.uid()) or public.is_marawis_admin());
drop policy if exists "Admins manage attendance" on public.attendance;
create policy "Admins manage attendance" on public.attendance
for all to authenticated
using (public.is_marawis_admin())
with check (public.is_marawis_admin());

-- Pembayaran: anggota melihat dan mengajukan pembayaran miliknya sendiri.
drop policy if exists "Read own payments or admin" on public.cash_payments;
create policy "Read own payments or admin" on public.cash_payments
for select to authenticated
using (member_id = (select auth.uid()) or public.is_marawis_admin());
drop policy if exists "Members submit own payments" on public.cash_payments;
create policy "Members submit own payments" on public.cash_payments
for insert to authenticated
with check (member_id = (select auth.uid()) and status = 'menunggu');
drop policy if exists "Admins manage payments" on public.cash_payments;
create policy "Admins manage payments" on public.cash_payments
for all to authenticated
using (public.is_marawis_admin())
with check (public.is_marawis_admin());

-- Pengeluaran hanya dapat dibaca dan dikelola admin.
drop policy if exists "Admins manage expenses" on public.cash_expenses;
create policy "Admins manage expenses" on public.cash_expenses
for all to authenticated
using (public.is_marawis_admin())
with check (public.is_marawis_admin());

